import * as fs from 'node:fs';
import * as path from 'node:path';
import { parse } from 'yaml';
import { resolveResource } from './resolve';

export const roleAgentName = (key: string): string =>
  `agteam-${key.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;

const marker = '# Generated by architecture-guard: codex role';
const featureNames = ['shell_tool', 'apps', 'plugins', 'memories', 'request_permissions_tool'];
const mapping = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

interface CodexRole {
  name: string;
  description: string;
  instructions: string;
  features: Record<string, false>;
  taskTag?: string;
  model?: string;
}

// JSON basic strings are TOML-compatible except JSON's short control escapes.
const tomlString = (value: string): string => JSON.stringify(value)
  .replace(/\\(?:["\\/bfnrt]|u[0-9a-fA-F]{4})/g, escape =>
    escape === '\\b' ? '\\u0008' : escape === '\\f' ? '\\u000c' : escape)
  .replace(/\u007f/g, '\\u007f');

export function validateProfile(profile: unknown): CodexRole[] {
  if (!mapping(profile) || !mapping(profile.roles)) throw new Error('roles must be a mapping');
  const topKeys = new Set(['version', 'topology', 'roles']);
  for (const key of Object.keys(profile)) if (!topKeys.has(key)) throw new Error(`Unsupported profile field: ${key}`);
  if (profile.version !== 1 || profile.topology !== 'codex-subagents') throw new Error('Expected version: 1 and topology: codex-subagents');
  const names = new Set<string>();
  const tags = new Set<string>();
  return Object.entries(profile.roles).map(([key, role]) => {
    if (!/^[a-zA-Z0-9_-]+$/.test(key) || !mapping(role)) throw new Error(`Invalid role: ${key}`);
    const name = roleAgentName(key);
    if (name === 'agteam-' || names.has(name)) throw new Error(`Role name collision or empty name: ${key}`);
    names.add(name);
    const allowed = new Set(['description', 'system_prompt', 'task_tag', 'features', 'model']);
    for (const field of Object.keys(role)) if (!allowed.has(field)) throw new Error(`Unsupported role restriction or field: ${key}.${field}`);
    if (typeof role.description !== 'string' || !role.description.trim() || typeof role.system_prompt !== 'string' || !role.system_prompt.trim()) {
      throw new Error(`Role ${key} requires description and system_prompt`);
    }
    if (!mapping(role.features)) throw new Error(`Role ${key} requires explicit features reductions`);
    const features: Record<string, false> = {};
    for (const [feature, value] of Object.entries(role.features)) {
      if (!featureNames.includes(feature) || value !== false) throw new Error(`Unsupported required feature reduction: ${key}.${feature}`);
      features[feature] = false;
    }
    let taskTag: string | undefined;
    if (role.task_tag !== undefined) {
      if (typeof role.task_tag !== 'string' || !/^[A-Z][A-Z0-9_]*$/.test(role.task_tag) || role.task_tag === 'ORCHESTRATION' || tags.has(role.task_tag)) {
        throw new Error(`Invalid or ambiguous task_tag: ${key}`);
      }
      taskTag = role.task_tag;
      tags.add(taskTag);
    }
    if (role.model !== undefined && (typeof role.model !== 'string' || !role.model.trim())) throw new Error(`Invalid model: ${key}`);
    return { name, description: role.description, instructions: role.system_prompt, features, taskTag,
      model: role.model === 'inherit' ? undefined : role.model as string | undefined };
  });
}

// Reject symlinks even when they point inside the workspace: never mutate another owner's alias.
export function assertRolePath(root: string, target: string): void {
  const relative = path.relative(root, target);
  if (!relative || relative.startsWith(`..${path.sep}`) || relative === '..' || path.isAbsolute(relative)) throw new Error(`Role path escapes target: ${target}`);
  let current = root;
  for (const part of relative.split(path.sep)) {
    current = path.join(current, part);
    if (fs.existsSync(current) || (() => { try { return fs.lstatSync(current).isSymbolicLink(); } catch { return false; } })()) {
      const stat = fs.lstatSync(current);
      if (stat.isSymbolicLink()) throw new Error(`Symlink role path is not allowed: ${current}`);
      if (current !== target && !stat.isDirectory()) throw new Error(`Role parent is not a directory: ${current}`);
    }
  }
}

function renderRole(role: CodexRole): string {
  const instructions = [role.instructions,
    'Use the lead-resolved Architecture Guard agent_execution contract supplied in the handoff. Refuse the task if required artifacts are unreadable or missing; do not enable tools to compensate. Obey parent session permissions. Role instructions are behavioral guidance, not a filesystem sandbox.',
    'Only the user grants approval. Leave human gates and external side effects with the lead. Work only on tasks and files assigned by the lead.',
    ...(role.taskTag ? [`Task tag: [${role.taskTag}].`] : [])].join('\n\n');
  return [marker, `name = ${tomlString(role.name)}`, `description = ${tomlString(role.description)}`,
    `developer_instructions = ${tomlString(instructions)}`,
    ...(role.model ? [`model = ${tomlString(role.model)}`] : []),
    '', '[features]', ...Object.keys(role.features).sort().map(key => `${key} = false`), ''].join('\n');
}

export function planCodexRoles(target: string, overwrite?: string, proposedProfile?: unknown) {
  const root = fs.realpathSync(target);
  const skills = path.join(root, '.codex', 'skills');
  assertRolePath(root, skills);
  if (!fs.existsSync(skills) || !fs.statSync(skills).isDirectory() || !fs.readdirSync(skills).some(name => name.startsWith('ag-'))) {
    throw new Error('No Codex skills are installed; install Codex skills before role setup');
  }
  const profilePath = path.join(root, '.architecture-guard', 'codex-agents.yml');
  assertRolePath(root, profilePath);
  const profile = proposedProfile === undefined
    ? parse(fs.existsSync(profilePath) ? fs.readFileSync(profilePath, 'utf8') : resolveResource('template', 'codex_agents_template', { target: root }).content)
    : proposedProfile;
  const roles = validateProfile(profile);
  const dir = path.join(root, '.codex', 'agents');
  assertRolePath(root, dir);
  if (fs.existsSync(dir) && !fs.statSync(dir).isDirectory()) throw new Error('Codex agents path must be a directory');
  const wanted = new Set(roles.map(role => `${role.name}.toml`));
  const entries = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
  for (const entry of new Set([...entries.filter(name => name.startsWith('agteam-') && name.endsWith('.toml')), ...wanted])) {
    const file = path.join(dir, entry);
    assertRolePath(root, file);
    if (!fs.existsSync(file)) continue;
    const owned = fs.statSync(file).isFile() && fs.readFileSync(file, 'utf8').startsWith(`${marker}\n`);
    if (wanted.has(entry) && !owned) throw new Error(`User-owned role conflict: ${entry}`);
  }
  const outputs = roles.map(role => ({ name: role.name, file: path.join(dir, `${role.name}.toml`), content: renderRole(role) }));
  const create: string[] = [], replace: string[] = [], retain: string[] = [], remove: string[] = [];
  for (const output of outputs) {
    if (!fs.existsSync(output.file)) create.push(output.file);
    else if (overwrite === 'skip' || overwrite === 'keep-both') retain.push(output.file);
    else replace.push(output.file);
  }
  for (const entry of entries) {
    if (!entry.startsWith('agteam-') || !entry.endsWith('.toml') || wanted.has(entry)) continue;
    const file = path.join(dir, entry);
    const owned = fs.statSync(file).isFile() && fs.readFileSync(file, 'utf8').startsWith(`${marker}\n`);
    if (owned && overwrite !== 'skip' && overwrite !== 'keep-both') remove.push(file);
    else retain.push(file);
  }
  return { dir, outputs, create, replace, retain, remove };
}

export function installCodexRoles(target: string, overwrite?: string, proposedProfile?: unknown) {
  const written: string[] = [];
  const removed: string[] = [];
  try {
    const plan = planCodexRoles(target, overwrite, proposedProfile);
    if (plan.outputs.length) fs.mkdirSync(plan.dir, { recursive: true });
    for (const output of plan.outputs) {
      if (plan.retain.includes(output.file)) continue;
      fs.writeFileSync(output.file, output.content);
      written.push(output.name);
    }
    for (const file of plan.remove) {
      fs.unlinkSync(file);
      removed.push(path.basename(file, '.toml'));
    }
    console.log(`Codex roles: wrote ${written.length}, removed ${removed.length}. Role setup does not activate coordinated execution. Parent permissions still apply.`);
    return { written, removed, errors: [] as string[] };
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    console.error(`Codex role setup failed: ${reason}. Changed: ${written.join(', ') || 'none'}; removed: ${removed.join(', ') || 'none'}.`);
    return { written, removed, errors: [reason] };
  }
}
