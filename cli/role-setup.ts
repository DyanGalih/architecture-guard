export function planRoles(desc: HostRoleDescriptor, target: string, overwrite?: string, proposedProfile?: unknown) {
  const root = fs.realpathSync(target);
  const skills = path.join(root, desc.skillsDir);
  assertRolePath(root, skills);
  if (!fs.existsSync(skills) || !fs.statSync(skills).isDirectory() || !fs.readdirSync(skills).some(name => name.startsWith('ag-'))) {
    throw new Error(`No ${desc.label} skills are installed; install ${desc.label} skills before role setup`);
  }
  const profilePath = path.join(root, '.architecture-guard', desc.profileName);
  assertRolePath(root, profilePath);
  const profile = proposedProfile === undefined
    ? parse(fs.existsSync(profilePath) ? fs.readFileSync(profilePath, 'utf8') : resolveResource('template', desc.templateName, { target: root }).content)
    : proposedProfile;
  const roles = desc.validateProfile(profile);
  const dir = path.join(root, desc.agentsDir);
  assertRolePath(root, dir);
  if (fs.existsSync(dir) && !fs.statSync(dir).isDirectory()) throw new Error(`${desc.label} agents path must be a directory`);
  const wanted = new Set(roles.map(role => `${role.name}${desc.fileExt}`));
  const entries = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
  for (const entry of new Set([...entries.filter(name => name.startsWith('agteam-') && name.endsWith(desc.fileExt)), ...wanted])) {
    const file = path.join(dir, entry);
    assertRolePath(root, file);
    if (!fs.existsSync(file)) continue;
    const content = fs.readFileSync(file, 'utf8');
    const owned = fs.statSync(file).isFile() && (content.startsWith(`${desc.marker}\n`) || content.includes(`\n${desc.marker}\n`));
    if (wanted.has(entry) && !owned) throw new Error(`User-owned role conflict: ${entry}`);
  }
  const outputs = roles.map(role => ({ name: role.name, file: path.join(dir, `${role.name}${desc.fileExt}`), content: desc.renderRole(role) }));
  const create: string[] = [], replace: string[] = [], retain: string[] = [], remove: string[] = [];
  for (const output of outputs) {
    if (!fs.existsSync(output.file)) create.push(output.file);
    else if (overwrite === 'skip' || overwrite === 'keep-both') retain.push(output.file);
    else replace.push(output.file);
  }
  for (const entry of entries) {
    if (!entry.startsWith('agteam-') || !entry.endsWith(desc.fileExt) || wanted.has(entry)) continue;
    const file = path.join(dir, entry);
    const content = fs.readFileSync(file, 'utf8');
    const owned = fs.statSync(file).isFile() && (content.startsWith(`${desc.marker}\n`) || content.includes(`\n${desc.marker}\n`));
    if (owned && overwrite !== 'skip' && overwrite !== 'keep-both') remove.push(file);
    else retain.push(file);
  }
  return { dir, outputs, create, replace, retain, remove };
}

export function installRoles(desc: HostRoleDescriptor, target: string, overwrite?: string, proposedProfile?: unknown) {
  const written: string[] = [];
  const removed: string[] = [];
  try {
    const plan = planRoles(desc, target, overwrite, proposedProfile);
    if (plan.outputs.length) fs.mkdirSync(plan.dir, { recursive: true });
    for (const output of plan.outputs) {
      if (plan.retain.includes(output.file)) continue;
      fs.writeFileSync(output.file, output.content);
      written.push(output.name);
    }
    for (const file of plan.remove) {
      fs.unlinkSync(file);
      removed.push(path.basename(file, desc.fileExt));
    }
    console.log(`${desc.label} roles: wrote ${written.length}, removed ${removed.length}. Role setup does not activate coordinated execution. Parent permissions still apply.`);
    return { written, removed, errors: [] as string[] };
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    console.error(`${desc.label} role setup failed: ${reason}. Changed: ${written.join(', ') || 'none'}; removed: ${removed.join(', ') || 'none'}.`);
    return { written, removed, errors: [reason] };
  }
}

